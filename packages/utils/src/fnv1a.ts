/** 32-bit FNV-1a hash of a string: fast, stable, not cryptographic. */
export const fnv1a = (value: string): number => {
	let hash = 2166136261;
	for (let index = 0; index < value.length; index += 1) {
		hash ^= value.charCodeAt(index);
		hash = Math.imul(hash, 16777619);
	}
	return hash >>> 0;
};
