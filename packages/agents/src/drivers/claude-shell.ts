import { createHash, randomUUID } from "node:crypto";
import {
	chmod,
	mkdir,
	readFile,
	rename,
	rm,
	writeFile,
} from "node:fs/promises";
import { homedir } from "node:os";
import { isAbsolute, join } from "node:path";
import { Effect } from "effect";

/**
 * The zsh Claude Code would run its Bash tool in, when it is the user's shell.
 * Claude Code prefers `$SHELL` when it names bash or zsh; other shells are left
 * to its own detection.
 */
export const claudeZshTarget = (
	env: Readonly<Record<string, string | undefined>>,
	platform: NodeJS.Platform = process.platform,
): string | null => {
	if (platform === "win32" || env.CLAUDE_CODE_SHELL?.trim()) return null;
	const shell = env.SHELL?.trim();
	if (!shell || !isAbsolute(shell)) return null;
	const name = shell.slice(shell.lastIndexOf("/") + 1);
	return name.includes("zsh") && !name.includes("bash") ? shell : null;
};

const shellQuote = (value: string): string =>
	`'${value.replaceAll("'", `'\\''`)}'`;

/**
 * Models write bash. With zsh's default NOMATCH, an unquoted pattern such as
 * `grep --include=*.ts` fails with "no matches found" instead of reaching the
 * command, so the wrapper turns it off to match bash.
 */
export const claudeZshWrapperScript = (zsh: string): string =>
	[
		"#!/bin/sh",
		"# Generated by Zuse for Claude Code's Bash tool.",
		`exec ${shellQuote(zsh)} -o NO_NOMATCH "$@"`,
		"",
	].join("\n");

const claudeShellDir = (): string =>
	join(homedir(), ".zuse", "provider-shells");

const ensureWrapper = (zsh: string, dir: string) =>
	Effect.tryPromise(async () => {
		const script = claudeZshWrapperScript(zsh);
		const id = createHash("sha256").update(zsh).digest("hex").slice(0, 12);
		// Claude Code only accepts an override whose path names zsh.
		const file = join(dir, `zsh-${id}`);
		const current = await readFile(file, "utf8").catch(() => null);
		if (current === script) {
			await chmod(file, 0o700);
			return file;
		}
		await mkdir(dir, { recursive: true, mode: 0o700 });
		const temp = `${file}.${randomUUID()}.tmp`;
		try {
			await writeFile(temp, script, { mode: 0o700 });
			// The creation mode is masked by the umask; the wrapper must be executable.
			await chmod(temp, 0o700);
			await rename(temp, file);
		} catch (error) {
			await rm(temp, { force: true });
			throw error;
		}
		return file;
	});

/**
 * Points Claude Code at a zsh wrapper with bash-like glob handling. Leaves the
 * environment unchanged when zsh is not the user's shell or the wrapper cannot
 * be written, so session start never depends on it.
 */
export const withClaudeZshShell = (
	env: Record<string, string | undefined>,
	dir: string = claudeShellDir(),
) => {
	const zsh = claudeZshTarget(env);
	if (zsh === null) return Effect.succeed(env);
	return ensureWrapper(zsh, dir).pipe(
		Effect.map((file) => ({ ...env, CLAUDE_CODE_SHELL: file })),
		Effect.catch(() => Effect.succeed(env)),
	);
};
